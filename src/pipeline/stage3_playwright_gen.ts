import * as fs from 'fs';
import * as path from 'path';
import { HeuristicDefect } from '../types';

export function executeStage3PlaywrightGen(
  defects: HeuristicDefect[],
  outputDir: string
): string[] {
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const generatedFiles: string[] = [];
  const defectsWithPlaywright = defects.filter((d) => d.playwrightAssertion);

  if (defectsWithPlaywright.length === 0) return generatedFiles;

  // Group by Heuristic
  const grouped: Record<string, HeuristicDefect[]> = {};
  for (const d of defectsWithPlaywright) {
    const key = d.ruleId.toLowerCase();
    if (!grouped[key]) grouped[key] = [];
    grouped[key].push(d);
  }

  for (const [ruleKey, items] of Object.entries(grouped)) {
    const specFileName = `heuristic_${ruleKey}.spec.ts`;
    const specFilePath = path.join(outputDir, specFileName);

    let content = `// AUTO-GENERATED BY heuristic-lint-action (Stage 3 Triangulation)
// Verifies live browser DOM affordances and prevents shift-left usability regressions.
import { test, expect } from '@playwright/test';

test.describe('Heuristic Validation: ${items[0].heuristic}', () => {
`;

    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      const relFile = path.basename(item.file);
      content += `
  test('Verify ${item.title} (${relFile}:${item.lineStart})', async ({ page }) => {
    // Defect ID: ${item.id} | Severity: ${item.severity}/4
    // Description: ${item.description.replace(/\n/g, ' ')}
    await page.goto('/');

    ${item.playwrightAssertion}
  });
`;
    }

    content += `});\n`;
    fs.writeFileSync(specFilePath, content, 'utf-8');
    generatedFiles.push(specFilePath);
  }

  return generatedFiles;
}
